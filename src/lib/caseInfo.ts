/**
 * 반응 적기 — 사례 정보가 섞였는지 기기 안에서 먼저 본다 (2026-11-27, 명세 6.1).
 *
 * AI 에 보내기 **전에** 확실한 단서만 잡는다: 나이, 학교·학년, 전화번호.
 * 잡히면 AI 에 보내지 않고 지우라고 알린다. (애매한 것은 AI 가 같은 호출에서 함께 본다.)
 * 상담자 자신의 반응("자해 장면이 떠올라 무섭다")은 사례 정보가 아니다 — 사건 낱말은 잡지 않는다.
 */

const RULES: { re: RegExp; what: string }[] = [
  { re: /\d{1,2}\s*(?:살|세)(?![가-힣])/, what: '나이' },
  { re: /(?:열|스무)\s*(?:한|두|세|네|다섯|여섯|일곱|여덟|아홉)?\s*살/, what: '나이' },
  { re: /[가-힣]{1,10}(?:초등학교|중학교|고등학교|대학교|초교|중교|고교)/, what: '학교' },
  { re: /[가-힣]{1,10}(?:초|중|고|여중|여고|공고|상고)\s*\d\s*학년/, what: '학교·학년' },
  { re: /(?:초|중|고)\s*\d\s*(?:학년)?(?![가-힣\d])/, what: '학년' },
  { re: /\d\s*학년\s*\d\s*반/, what: '학년·반' },
  { re: /\d{2,3}[-.\s]?\d{3,4}[-.\s]?\d{4}/, what: '전화번호' },
];

/** 찾은 단서 종류 (없으면 빈 배열) — 순수 함수 */
export function findCaseInfo(text: string): string[] {
  const found: string[] = [];
  for (const r of RULES) if (r.re.test(text) && !found.includes(r.what)) found.push(r.what);
  return found;
}

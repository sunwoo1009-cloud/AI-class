export interface Guess {
  id: ReactionType;
  score: number;
}

/** 점수가 높은 순으로 최대 두 개. 하나도 안 맞으면 빈 배열. */
export function guessReactions(text: string): Guess[] {
  const t = text.normalize('NFC').trim();
  if (!t) return [];
  const scores: Guess[] = (Object.keys(LEXICON) as ReactionType[]).map((id) => ({
    id,
    score: LEXICON[id].reduce((sum, [re, w]) => sum + (re.test(t) ? w : 0), 0),
  }));
  const hits = scores.filter((g) => g.score > 0).sort((a, b) => b.score - a.score);
  if (hits.length === 0) return [];
  // 두 번째는 첫 번째와 엇비슷할 때만 함께 보여준다
  const [first, second] = hits;
  return second && second.score >= first.score * 0.6 ? [first, second] : [first];
}
